// Assembles dist/mcp/filmcraft-mcp.mjs: a standalone MCP (stdio) server.
//
// It reuses the host modules verbatim — same engine wrapper, snapshots, registry,
// jobs and previews as the panel — so the panel and an MCP client share one
// workspace, one undo stack and one job list. Only src/host/99-plugin.js (the
// DSH loader glue) is left out; src/mcp/*.js is appended in filename order.
// Same module rules as build-native.mjs: shared scope, no import/export.
import { mkdirSync, readFileSync, readdirSync, writeFileSync, chmodSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const read = (dir, skip) => readdirSync(join(root, 'src', dir)).filter((n) => n.endsWith('.js') && !(skip || []).includes(n)).sort()
  .map((name) => '// ── ' + dir + '/' + name + ' ' + '─'.repeat(Math.max(2, 60 - name.length)) + '\n' + readFileSync(join(root, 'src', dir, name), 'utf8').trimEnd())

const body = [
  '#!/usr/bin/env node',
  '// GENERATED by scripts/build-mcp.mjs — edit src/host/*.js and src/mcp/*.js instead.',
  "import { readFileSync, statSync, existsSync, readdirSync, mkdirSync, writeFileSync, appendFileSync, openSync, closeSync, copyFileSync, renameSync, rmSync, unlinkSync } from 'node:fs'",
  "import { spawnSync, spawn } from 'node:child_process'",
  '',
  ...read('host', ['99-plugin.js']),
  '',
  ...read('mcp'),
  '',
].join('\n\n')

const out = join(root, 'dist', 'mcp', 'filmcraft-mcp.mjs')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, body, 'utf8')
try { chmodSync(out, 0o755) } catch (_) { }
console.log('wrote ' + out.replace(root, '.') + ' (' + Math.round(body.length / 1024) + ' KB)')
